#!/usr/bin/env python3
"""sn_learn.py — turn the module knowledge base into a timeboxed study brief.

Subcommands
    list                      table of modules
    brief <module-id>         markdown study brief (print or --out)
    brief --all               every brief into docs/generated/
    plan <module-id>          minute-by-minute schedule (default start 09:00)
    quiz <module-id>          questions with collapsed answers
    sources [--check]         official-resource ladder; --check re-tests the URLs
    schema                    what a module entry must contain (for contributors)

Design rules (deliberate):
  * Standard library only. This must run on a bare PDI-adjacent laptop.
  * Nothing here invents a ServiceNow fact: the KB says where to look on the
    instance, the probe (scripts/sn_probe.js) says what your instance actually
    contains, and every brief points at official docs search + Now Learning.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES = ROOT / "data" / "modules.json"
SOURCES = ROOT / "data" / "sources.json"

AGENT_STAMP = (
    "> **Agent:** buffy (mimo-v2.6-flash) · **Branch:** buffy-mimo-v2.6-flash-2026-11-04 "
    "· **Updated:** 2026-11-04"
)


def load(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        sys.exit(f"missing {path} — run from the repo root")
    except json.JSONDecodeError as exc:
        sys.exit(f"{path} is not valid JSON: {exc}")


def by_id(kb: dict, module_id: str) -> dict:
    for mod in kb["modules"]:
        if mod["id"] == module_id:
            return mod
    ids = ", ".join(m["id"] for m in kb["modules"])
    sys.exit(f"unknown module '{module_id}'. Known: {ids}")


def docs_url(sources: dict, module_id: str) -> str:
    q = sources["per_module_docs_search"]["queries"].get(module_id, module_id)
    return sources["per_module_docs_search"]["pattern"].replace("<query>", q)


def fields_block(mod: dict) -> str:
    f = mod.get("fields", {})
    out = ["### Fields — critical vs useful vs optional", ""]
    crit = f.get("critical", [])
    if crit:
        out += ["**Critical** (get these wrong and the module misbehaves; mandatory-ness varies by instance):", ""]
        for item in crit:
            if isinstance(item, dict):
                out.append(f"- `{item.get('field','?')}` — {item.get('why','')}")
            else:
                out.append(f"- `{item}`")
        out.append("")
    for label, key in (("Useful", "useful"), ("Optional / nice to have", "optional"),
                       ("Related lists worth configuring", "related_lists")):
        vals = f.get(key) or []
        if vals:
            out.append(f"**{label}:** " + ", ".join(f"`{v}`" if " " not in v else v for v in vals))
            out.append("")
    out += [
        "> Mandatory is not a guess. Confirm it: `All > System Definition > Tables & Columns`, pick the table, "
        "filter the columns on `Mandatory = true`. The probe script does this for every table below in one run.",
        "",
    ]
    return "\n".join(out)


def brief(kb: dict, sources: dict, mod: dict) -> str:
    gs = mod.get("guided_setup", {})
    oob = mod.get("oob", {})
    tb = mod.get("timebox_min", {})
    total = sum(tb.values()) if tb else 0
    lines = [
        f"# {mod['name']} — rapid study brief",
        "",
        AGENT_STAMP,
        "",
        f"**Module id:** `{mod['id']}` · **App:** {mod.get('app','')} · **Primary table:** `{mod.get('primary_table','')}` "
        f"· **Suggested timebox:** {total} min",
        "",
        "> Generated by `scripts/sn_learn.py brief`. Source of truth for the schema: your instance "
        "(run `scripts/sn_probe.js`), not this file.",
        "",
        "## Why this module first",
        "",
        mod.get("why", ""),
        "",
        "## The 60-second orientation",
        "",
        f"- Primary table: `{mod.get('primary_table','')}`",
        f"- Tables that matter: {', '.join('`'+t+'`' for t in mod.get('tables', []))}",
        f"- Roles to test with: {', '.join('`'+r+'`' for r in mod.get('roles', []))}",
        "",
        "## Breadcrumbs (where to actually click)",
        "",
    ]
    lines += [f"{i}. {b}" for i, b in enumerate(mod.get("breadcrumbs", []), 1)]
    lines += ["", "## Guided Setup", ""]
    if gs.get("available"):
        lines.append(f"- **Exists:** yes — start at `{gs.get('path','(find it with the probe)')}`")
        if gs.get("confidence") == "verify":
            lines.append("- **Confidence:** verify. Menu labels move between releases. Find it for certain with: "
                         "`sn_probe.js` lists every module whose name contains \"Guided Setup\".")
        if gs.get("note"):
            lines.append(f"- {gs['note']}")
    else:
        lines.append(f"- **Exists:** no dedicated guided setup. {gs.get('note','')}".rstrip())
    lines += ["", "## Out of the box (do not rebuild what already ships)", ""]
    for label, key in (("Flows", "flows"), ("Playbooks", "playbooks"), ("Integrations", "integrations"),
                       ("Metrics", "metrics"), ("Dashboards", "dashboards")):
        vals = oob.get(key) or []
        if vals:
            lines.append(f"**{label}:**")
            lines += [f"- {v}" for v in vals]
            lines.append("")
    lines += [fields_block(mod), "## Must know (the 5 facts that unlock the rest)", ""]
    lines += [f"- {m}" for m in mod.get("must_know", [])]
    lines += ["", "## Common mistakes", ""]
    lines += [f"- {m}" for m in mod.get("mistakes", [])]
    lines += ["", "## Labs", ""]
    labs = mod.get("labs") or []
    lines += [f"- [`{l}`](../{l})" for l in labs] if labs else ["- (no lab mapped yet — build one and add it to `data/modules.json`)"]
    lines += [
        "",
        "## Timebox",
        "",
        "| Gate | Minutes | You are done when |",
        "|---|---|---|",
        f"| Orient | {tb.get('orient','?')} | you can name the primary table and open 3 lists without searching |",
        f"| Model | {tb.get('model','?')} | one page: tables, states, roles, one diagram |",
        f"| Practice | {tb.get('practice','?')} | the lab works, and you broke it once and fixed it |",
        f"| Prove | {tb.get('prove','?')} | the quiz answered from memory + probe sheet attached |",
        "",
        "## Official sources to read (in this order)",
        "",
        f"1. Docs (search): {docs_url(sources, mod['id'])}",
        "2. Now Learning: https://learning.servicenow.com/lxp — search the module name; free fundamentals first",
        "3. Now Create Success Pack for this app: https://nowcreate.servicenow.com/ (partner/customer login)",
        "4. Support KB for any error you actually hit: https://support.servicenow.com/now",
        "",
        "> Third-party blogs/videos come *after* step 1-4, and never as the citation of record.",
        "",
        "## Teach-back (this is the actual test)",
        "",
        "Write, without looking: 5 sentences a non-technical colleague would understand, then one diagram "
        "with 4 boxes and 3 arrows. Then re-open the docs and correct it. If your correction changes a box, "
        "you had not learned it yet — redo the Practice gate.",
        "",
    ]
    return "\n".join(lines)


def plan(mod: dict, start: str) -> str:
    tb = mod.get("timebox_min", {})
    t = dt.datetime.strptime(start, "%H:%M")
    rows = [("Orient", "read breadcrumbs + open the lists", tb.get("orient", 0)),
            ("Model", "tables/states/roles → one page + diagram", tb.get("model", 0)),
            ("Practice", "do the lab; break it once", tb.get("practice", 0)),
            ("Prove", "quiz from memory + probe sheet", tb.get("prove", 0))]
    out = [f"# {mod['name']} — plan starting {start}", "", AGENT_STAMP, "",
           "| Start | End | Gate | What you do |", "|---|---|---|---|"]
    for gate, what, mins in rows:
        end = t + dt.timedelta(minutes=mins)
        out.append(f"| {t:%H:%M} | {end:%H:%M} | {gate} | {what} |")
        t = end
    out += ["", f"Total: {sum(m for _, _, m in rows)} minutes. Stop at the end time even if unfinished — "
                "whatever you did not finish becomes tomorrow's Orient gate."]
    return "\n".join(out)


def quiz(mod: dict) -> str:
    out = [f"# {mod['name']} — recall check", "", AGENT_STAMP, "",
           "Answer out loud before opening each answer. One word answers do not count.", ""]
    for i, q in enumerate(mod.get("quiz", []), 1):
        out += [f"**{i}. {q}**", "", "<details><summary>Answer</summary>", "",
                "Answer from your instance + docs, then check it against the sheet from `sn_probe.js`. "
                "If you cannot answer, you skipped the Model gate.", "", "</details>", ""]
    return "\n".join(out)


def sources_report(sources: dict, check: bool) -> str:
    out = ["# Official ServiceNow resources", "", AGENT_STAMP, "",
           f"**Rule:** {sources['_meta']['rule']}", "", "## Ladder (read in this order)", ""]
    for s in sources["ladder"]:
        out += [f"### {s['rank']}. {s['name']}", "", f"- {s['url']}", f"- Use for: {s['use_for']}",
                f"- Access: {s.get('access','')}"]
        if s.get("canonical_note"):
            out.append(f"- Note: {s['canonical_note']}")
        if s.get("why_it_matters"):
            out.append(f"- Why it matters: {s['why_it_matters']}")
        if check:
            out.append(f"- HTTP check {dt.date.today()}: **{http_status(s['url'])}**")
        else:
            out.append(f"- Status on {sources['_meta']['created']}: {s.get('status_2026_11_04','')}")
        out.append("")
    out += ["## Per-module docs search", ""]
    for mid, q in sources["per_module_docs_search"]["queries"].items():
        out.append(f"- `{mid}` → {sources['per_module_docs_search']['pattern'].replace('<query>', q)}")
    out += ["", "## Study order", ""] + [f"{i}. {step}" for i, step in enumerate(sources["study_order"], 1)]
    out += ["", f"Citation format: `{sources['citation_format']}`", ""]
    return "\n".join(out)


def http_status(url: str, timeout: int = 15) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (sn-learn source check)"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return str(resp.status)
    except urllib.error.HTTPError as exc:
        return f"HTTP {exc.code}"
    except Exception as exc:  # noqa: BLE001 - report, never crash the report
        return f"unreachable ({type(exc).__name__})"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    sub.add_parser("list", help="list modules")
    p_brief = sub.add_parser("brief", help="render a study brief")
    p_brief.add_argument("module", nargs="?")
    p_brief.add_argument("--all", action="store_true")
    p_brief.add_argument("--out", type=Path)
    p_plan = sub.add_parser("plan", help="timeboxed schedule")
    p_plan.add_argument("module")
    p_plan.add_argument("--start", default="09:00")
    p_quiz = sub.add_parser("quiz", help="recall check")
    p_quiz.add_argument("module")
    p_src = sub.add_parser("sources", help="official resource ladder")
    p_src.add_argument("--check", action="store_true", help="re-test every base URL now")
    sub.add_parser("schema", help="required keys for a module entry")

    args = ap.parse_args()
    kb = load(MODULES)

    if args.cmd == "list":
        print(f"{'id':24} {'app':22} {'guided setup':14} tables")
        print("-" * 100)
        for m in kb["modules"]:
            gs = "yes" if m.get("guided_setup", {}).get("available") else "no"
            print(f"{m['id']:24} {m.get('app',''):22} {gs:14} {', '.join(m.get('tables', [])[:4])}")
        return

    if args.cmd == "brief":
        src = load(SOURCES)
        if args.all:
            outdir = args.out or (ROOT / "docs" / "generated")
            outdir.mkdir(parents=True, exist_ok=True)
            for m in kb["modules"]:
                p = outdir / f"brief-{m['id']}.md"
                p.write_text(brief(kb, src, m), encoding="utf-8")
                print(f"wrote {p.relative_to(ROOT)}")
            return
        if not args.module:
            sys.exit("brief needs a module id, or --all")
        text = brief(kb, src, by_id(kb, args.module))
        if args.out:
            args.out.parent.mkdir(parents=True, exist_ok=True)
            args.out.write_text(text, encoding="utf-8")
            print(f"wrote {args.out}")
        else:
            print(text)
        return

    if args.cmd == "plan":
        print(plan(by_id(kb, args.module), args.start))
        return

    if args.cmd == "quiz":
        print(quiz(by_id(kb, args.module)))
        return

    if args.cmd == "sources":
        print(sources_report(load(SOURCES), args.check))
        return

    if args.cmd == "schema":
        print(json.dumps(_schema(), indent=2))
        return


def _schema() -> dict:
    return {
        "id": "kebab-case, referenced by every command",
        "name": "human label",
        "app": "product family",
        "confidence": "high | verify — 'verify' prints a warning in the brief",
        "why": "one sentence: why learn this before the others",
        "primary_table": "the table a beginner should open first",
        "tables": ["..."],
        "roles": ["..."],
        "breadcrumbs": ["All > ... (starting point, not a guarantee)"],
        "guided_setup": {"available": "bool", "path": "All > ...", "confidence": "verify", "note": ""},
        "oob": {"flows": [], "playbooks": [], "integrations": [], "metrics": [], "dashboards": []},
        "fields": {"critical": [{"field": "", "why": ""}], "useful": [], "optional": [], "related_lists": []},
        "must_know": ["..."],
        "mistakes": ["..."],
        "labs": ["labs/....md"],
        "timebox_min": {"orient": 10, "model": 20, "practice": 45, "prove": 10},
        "quiz": ["..."],
    }


if __name__ == "__main__":
    main()
